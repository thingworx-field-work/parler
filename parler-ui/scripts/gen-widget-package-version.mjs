/**
 * Writes `parler-ui/lib/widgetPackageVersion.js` from `parler-ui-widget/input/widgets.json` `version`.
 * Run from repo root via `parler-ui` npm `build:tw`, or from `parler-ui-widget` sync (which invokes this first).
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const parlerUiRoot = path.resolve(__dirname, "..");
const widgetsJson = path.resolve(parlerUiRoot, "..", "parler-ui-widget", "input", "widgets.json");
const outFile = path.join(parlerUiRoot, "lib", "widgetPackageVersion.js");

if (!fs.existsSync(widgetsJson)) {
  console.error("gen-widget-package-version: missing", widgetsJson);
  process.exit(1);
}
const raw = fs.readFileSync(widgetsJson, "utf8");
const j = JSON.parse(raw);
const v = j && typeof j.version === "string" ? j.version.trim() : "";
if (!/^\d+\.\d+\.\d+/.test(v)) {
  console.error("gen-widget-package-version: invalid widgets.json version:", v);
  process.exit(1);
}
const body = `/**
 * ThingWorx widget extension package version (Composer import), from \`parler-ui-widget/input/widgets.json\`.
 * Regenerated by \`npm run build:tw\` and by \`parler-ui-widget\` \`npm run sync\` — do not edit by hand.
 */
export const WIDGET_PACKAGE_VERSION = ${JSON.stringify(v)};
`;
fs.writeFileSync(outFile, body, "utf8");
console.log("gen-widget-package-version:", v, "→", path.relative(parlerUiRoot, outFile));
